PRIORITY = {
    "神话神魔剧":8,"公案清官剧":7,"英雄侠义剧":6,"历史风云剧":5,
    "宫廷权谋剧":4,"爱情婚姻剧":3,"家庭伦理剧":2,"生活风俗剧":1,
}

def classify(sid):
    s = scripts.get(sid,{})
    title = s.get('title','')
    summary = s.get('plot_summary','')
    char_names = set(c.get('name','').strip() for c in s.get('characters',[])) - {'龙套',''}
    text = title+' '+summary
    scores = {cat:0.0 for cat in CHAR_RULES}
    for cat, names in CHAR_RULES.items():
        for name in names:
            if name in char_names: scores[cat] += 3
    for cat, kws in KW_RULES.items():
        for kw in kws:
            if kw in text: scores[cat] += 1
    best = max(scores.values())
    if best == 0: return "生活风俗剧", scores
    candidates = [c for c,v in scores.items() if v==best]
    return max(candidates, key=lambda c:PRIORITY[c]), scores

categories = [classify(sid)[0] for sid in ids]
cat_dist = Counter(categories)
print("分类结果：")
for cat, cnt in sorted(cat_dist.items(), key=lambda x:-x[1]):
    print(f"  {cat}: {cnt} ({cnt/len(ids)*100:.1f}%)")

# 抽样验证
