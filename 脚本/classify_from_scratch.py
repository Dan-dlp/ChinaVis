for i,sid in enumerate(ids): by_cat[categories[i]].append(sid)
print("\n=== 各类抽样（6个）===")
for cat in sorted(CHAR_RULES.keys()):
    samples = random.sample(by_cat[cat], min(6, len(by_cat[cat])))
    print(f"\n【{cat}】 n={len(by_cat[cat])}")
